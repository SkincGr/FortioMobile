const translations: Record<Language, Record<string, string>> = { el, en, fr }

type I18nContextType = {
  language: Language
  setLanguage: (l: Language) => void
  autoTranslate: boolean
  setAutoTranslate: (v: boolean) => void
  t: (key: keyof typeof el) => string
}

const I18nContext = createContext<I18nContextType>({
  language: 'el',
  setLanguage: () => {},
  autoTranslate: false,
  setAutoTranslate: () => {},
  t: (key) => el[key],
})

// Mirrors the provider's language for plain formatting helpers (lib/cityDisplay.ts)
// that run inside components already re-rendered by a language change.
let activeLanguage: Language = 'el'
export function currentLanguage(): Language {
  return activeLanguage
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [language, setLang] = useState<Language>('el')
  const [autoTranslate, setAutoTrans] = useState(false)
  activeLanguage = language

  useEffect(() => {
    SecureStore.getItemAsync(LANG_KEY).then(v => {
      if (v === 'el' || v === 'en' || v === 'fr') setLang(v as Language)
    })
    SecureStore.getItemAsync(AUTO_TRANSLATE_KEY).then(v => {
      if (v === 'true') setAutoTrans(true)
    })
  }, [])

  function setLanguage(l: Language) {
    setLang(l)
    SecureStore.setItemAsync(LANG_KEY, l)
  }

  function setAutoTranslate(v: boolean) {
    setAutoTrans(v)
    SecureStore.setItemAsync(AUTO_TRANSLATE_KEY, v ? 'true' : 'false')
  }

  function t(key: keyof typeof el): string {
    return translations[language][key] ?? el[key]
  }

  return (
    <I18nContext.Provider value={{ language, setLanguage, autoTranslate, setAutoTranslate, t }}>
      {children}
    </I18nContext.Provider>
  )
}

let transQueue: Array<() => Promise<void>> = []
let transProcessing = false

async function processTransQueue() {
  if (transProcessing) return
  transProcessing = true
  while (transQueue.length > 0) {
    const fn = transQueue.shift()
    if (fn) await fn()
    await new Promise(r => setTimeout(r, 100)) // 100ms delay to prevent 429 Too Many Requests
  }
  transProcessing = false
}

export async function translateText(text: string, targetLang: string): Promise<string> {
  if (!text.trim()) return text
  return new Promise((resolve) => {
    transQueue.push(async () => {
      try {
        const url = `https://translate.googleapis.com/translate_a/single?client=gtx&sl=auto&tl=${targetLang}&dt=t&q=${encodeURIComponent(text)}`
        const res = await fetch(url)
        if (!res.ok) throw new Error(`HTTP ${res.status}`)
        const json = await res.json()
        resolve(json[0].map((chunk: any) => chunk[0]).join(''))
      } catch (e) {
        console.warn('Translation failed:', e)
        resolve(text) // return original text on failure
      }
    })
    processTransQueue()
  })
}

export function useI18n() {
  return useContext(I18nContext)
}
