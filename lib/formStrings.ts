const DICTS = {
  el: { ...FORM_EL, ...FORM_MOBILE_EL },
  en: { ...FORM_EN, ...FORM_MOBILE_EN },
  fr: FORM_FR,
} as const

function lookup(dict: unknown, key: string): string | undefined {
  const [section, name] = key.split('.')
  const value = (dict as Record<string, Record<string, unknown> | undefined>)[section]?.[name]
  return typeof value === 'string' ? value : undefined
}

/** Κείμενο της φόρμας στη γλώσσα της εφαρμογής· γαλλικά → αγγλικά → ελληνικά → το ίδιο το κλειδί */
export function formText(language: 'el' | 'en' | 'fr', key: string): string {
  return lookup(DICTS[language], key) ?? lookup(DICTS.en, key) ?? lookup(DICTS.el, key) ?? key
}
